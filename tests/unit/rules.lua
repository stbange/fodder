local design = dofile(arg[1])
assert(design.arena.name == "The Broken Ford")
assert(#design.battles == 3 and #design.upgrades == 3)
assert(#design.arena.obstacles > 4)
assert(design.battles[1].enemy_damage < design.battles[3].enemy_damage)
assert(design.battles[1].flankers > 0 and design.battles[1].flankers < design.battles[3].flankers)

local naked = design.effects(0, 0, 0)
local earned = design.effects(1, 1, 1)
local experienced = design.effects(2, 2, 2)
local veteran = design.effects(1000, 1000, 1000)
assert(naked.recovery == 1 and naked.block_cost == 1 and naked.dressing == 0)
assert(naked.recovery < earned.recovery and earned.recovery < experienced.recovery)
assert(naked.block_cost > earned.block_cost and earned.block_cost > experienced.block_cost)
assert(naked.dressing < earned.dressing and earned.dressing < experienced.dressing)
assert(veteran.recovery < 1.55 and veteran.block_cost > 0.54 and veteran.dressing < 38)
assert(experienced.recovery - earned.recovery < earned.recovery - naked.recovery)
